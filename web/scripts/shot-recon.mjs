// Screenshots of the intake + reconstruction walkthrough:  node scripts/shot-recon.mjs <outDir>
import { chromium } from 'playwright';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const logs = [];
page.on('console', (m) => m.type() === 'error' && logs.push(m.text()));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://localhost:5173/', { waitUntil: 'load' });
await page.waitForSelector('.intake', { timeout: 120000 });
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/r-0-intake.png` });
await page.click('button:has-text("Reconstruct")');
await page.waitForTimeout(5000);
await page.screenshot({ path: `${out}/r-1-body.png` });
await page.click('.step-actions .primary');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/r-2-skeleton.png` });
await page.click('.step-actions .primary');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/r-3-lungs.png` });
await page.click('.step-actions .primary');
await page.click('.step-actions .primary');
await page.waitForTimeout(1500);
await page.hover('.legend-list button >> nth=0');
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/r-5-vessels.png` });
console.log(logs.slice(-6).join('\n'));
await browser.close();
