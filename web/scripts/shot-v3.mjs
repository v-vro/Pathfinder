import { chromium } from 'playwright';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const logs = [];
page.on('console', (m) => (m.type() === 'error') && logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://localhost:5173/planner?plan', { waitUntil: 'load' });
await page.waitForFunction(() => !document.querySelector('.loading'), null, { timeout: 120000 });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/v3-1-start.png` });
await page.mouse.move(640, 380);
await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/v3-2-aim.png` });
await page.click('text=Find safest path');
await page.waitForTimeout(1800);
await page.screenshot({ path: `${out}/v3-3-plan.png` });
for (let i = 0; i < 7; i++) await page.keyboard.press('ArrowRight');
await page.keyboard.press('ArrowUp');
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/v3-4-head.png` });
await page.keyboard.press('0');
await page.keyboard.press('b');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/v3-5-body.png` });
console.log(logs.slice(-8).join('\n'));
await browser.close();
