import { chromium } from 'playwright';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5173/', { waitUntil: 'load' });
await page.waitForFunction(() => !document.querySelector('.loading'), null, { timeout: 120000 });
await page.click('text=Find safest path');
await page.waitForTimeout(1200);
for (let i = 0; i < 8; i++) await page.keyboard.press('ArrowRight');
for (let i = 0; i < 4; i++) await page.keyboard.press('ArrowUp');
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/7-head-right.png` });
await page.keyboard.press('0');
await page.click('text=Explain to patient');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/8-patient.png` });
await browser.close();
